"""Download BOTH WMT26 recipe training resources and the official WMT26 testset.

The training default is a small Tatoeba corpus explicitly listed in the WMT26
English-Icelandic train recipe. Its URL is the one generated by MTData's OPUS
index. We download that exact source directly, avoiding the entire recipe.
"""
from __future__ import annotations

import argparse
import io
import itertools
import json
import random
import zipfile
from pathlib import Path

from .common import ROOT, read_jsonl, sha256, source_key, write_json, write_jsonl

RECIPE_URL = "https://www.statmt.org/wmt26/mtdata/mtdata.recipes.wmt26-constrained.yml"
TRAIN_ID = "OPUS-tatoeba-v20230412-eng-isl"
TRAIN_URL = "https://object.pouta.csc.fi/OPUS-Tatoeba/v2023-04-12/moses/en-is.txt.zip"
MTDATA_INDEX_URL = "https://raw.githubusercontent.com/thammegowda/mtdata/main/mtdata/resource/opus_index.tsv"
TEST_REPO = "wmt-conference/wmt26-general-mt"


def download(url: str, destination: Path) -> Path:
    import requests

    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.is_file() and destination.stat().st_size:
        return destination
    temporary = destination.with_suffix(destination.suffix + ".part")
    print(f"Downloading {url}", flush=True)
    with requests.get(url, stream=True, timeout=(30, 180)) as response:
        response.raise_for_status()
        with temporary.open("wb") as handle:
            for block in response.iter_content(1024 * 1024):
                if block:
                    handle.write(block)
    temporary.replace(destination)
    return destination


def english_icelandic_test_rows(records: list[dict], *, max_chars: int, allow_multimodal: bool) -> list[dict]:
    result = []
    for item in records:
        if item.get("src_lang", "").split("_")[0] not in {"eng", "en"}:
            continue
        if item.get("tgt_lang", "").split("_")[0] not in {"isl", "is"}:
            continue
        if not allow_multimodal and (item.get("video") or item.get("screenshot")):
            continue
        source = item.get("src_text", "").strip()
        if not source or (max_chars and len(source) > max_chars):
            continue
        refs = item.get("refs") or {}
        # Use official references only, never a submitted system hypothesis.
        refs = {key: value for key, value in refs.items() if isinstance(value, str) and value.strip()}
        preferred = next((key for key in ("refA", "refB", "refPE") if key in refs), None)
        if preferred is None and refs:
            preferred = sorted(refs)[0]
        result.append({
            "id": item["doc_id"], "source": source,
            "reference": refs[preferred] if preferred else None,
            "reference_key": preferred, "references": refs,
            "src_lang": "en", "tgt_lang": "is", "split": "test", "usage": "evaluation_only",
            "dataset": "WMT26-General-MT-official-test",
            "doc_id": item["doc_id"], "domain": item.get("domain"),
            "instruction": item.get("prompt_instruction"),
        })
    return result


def prepare_test(args) -> None:
    import requests

    raw = ROOT / "data" / "raw" / "wmt26"
    revision_file = raw / "revision.json"
    if revision_file.exists():
        revision = json.loads(revision_file.read_text(encoding="utf-8"))["commit"]
    else:
        response = requests.get(f"https://api.github.com/repos/{TEST_REPO}/commits/main", timeout=60)
        response.raise_for_status()
        revision = response.json()["sha"]
        write_json(revision_file, {"repository": TEST_REPO, "commit": revision})
    url = f"https://raw.githubusercontent.com/{TEST_REPO}/{revision}/data/wmt26-genmt.jsonl"
    raw_file = download(url, raw / "wmt26-genmt.jsonl")
    records = read_jsonl(raw_file)
    all_direction = english_icelandic_test_rows(records, max_chars=0, allow_multimodal=True)
    selected = english_icelandic_test_rows(records, max_chars=args.max_chars, allow_multimodal=args.allow_multimodal)
    if args.limit:
        selected = selected[:args.limit]
    if not selected:
        raise RuntimeError("No English-Icelandic test documents survived the selected filters.")
    destination = ROOT / "data" / "processed" / "test.jsonl"
    write_jsonl(destination, selected)
    write_json(destination.with_suffix(".manifest.json"), {
        "url": url, "revision": revision, "raw_sha256": sha256(raw_file),
        "processed_sha256": sha256(destination), "usage": "evaluation_only",
        "all_direction_documents": len(all_direction), "selected_documents": len(selected),
        "documents_with_reference": sum(bool(row["reference"]) for row in selected),
        "filters": {"max_source_chars": args.max_chars, "limit": args.limit, "allow_multimodal": args.allow_multimodal},
        "scope": "filtered document-level smoke test, NOT the complete official WMT26 benchmark",
    })
    print(f"Saved {len(selected)} test documents to {destination}", flush=True)


def read_training_zip(path: Path) -> list[tuple[str, str]]:
    with zipfile.ZipFile(path) as archive:
        english = [name for name in archive.namelist() if name.endswith(".en")]
        icelandic = [name for name in archive.namelist() if name.endswith(".is")]
        if len(english) != 1 or len(icelandic) != 1:
            raise ValueError(f"Expected one .en and one .is file; found {english}, {icelandic}.")
        # Stream known members rather than extractall (no archive path traversal).
        with archive.open(english[0]) as en_file, archive.open(icelandic[0]) as is_file:
            en_lines = io.TextIOWrapper(en_file, encoding="utf-8")
            is_lines = io.TextIOWrapper(is_file, encoding="utf-8")
            pairs = []
            for source, target in itertools.zip_longest(en_lines, is_lines):
                if source is None or target is None:
                    raise ValueError("Training parallel files have unequal line counts.")
                pairs.append((source.strip(), target.strip()))
            return pairs


def prepare_train(args) -> None:
    import yaml

    raw = ROOT / "data" / "raw" / "train"
    recipe = download(RECIPE_URL, raw / "mtdata.recipes.wmt26-constrained.yml")
    content = yaml.safe_load(recipe.read_text(encoding="utf-8"))
    if isinstance(content, dict):
        recipes = content.get("recipes", content)
        if isinstance(recipes, dict):
            recipes = [dict(value, id=key) for key, value in recipes.items()]
    else:
        recipes = content
    matches = [item for item in recipes if item.get("id") == "wmt26-eng-isl"]
    if not matches or TRAIN_ID not in matches[0].get("train", []):
        raise ValueError(f"{TRAIN_ID} is not in the downloaded WMT26 English-Icelandic train recipe.")
    index = download(MTDATA_INDEX_URL, raw / "mtdata-opus-index.tsv")
    if "Tatoeba\tv2023-04-12\ten\tis" not in index.read_text(encoding="utf-8"):
        raise ValueError("Training source/version not present in the MTData OPUS index.")
    archive = download(TRAIN_URL, raw / "Tatoeba-v2023-04-12-en-is.zip")
    pairs = read_training_zip(archive)
    test_file = ROOT / "data" / "processed" / "test.jsonl"
    if not test_file.exists():
        raise ValueError("Prepare the WMT26 test data first, so training sources can be checked against it.")
    excluded = {source_key(row["source"]) for row in read_jsonl(test_file)}
    # Also exclude ALL English-Icelandic documents in the downloaded official testset.
    full_test = ROOT / "data" / "raw" / "wmt26" / "wmt26-genmt.jsonl"
    for row in english_icelandic_test_rows(read_jsonl(full_test), max_chars=0, allow_multimodal=True):
        excluded.add(source_key(row["source"]))
    seen = set()
    rows = []
    for index_number, (source, target) in enumerate(pairs):
        key = source_key(source)
        if not source or not target or key in seen or key in excluded:
            continue
        if args.max_chars and max(len(source), len(target)) > args.max_chars:
            continue
        seen.add(key)
        rows.append({
            "id": f"{TRAIN_ID}:{index_number}", "source": source, "reference": target,
            "src_lang": "en", "tgt_lang": "is", "dataset": TRAIN_ID,
            "wmt26_recipe": "wmt26-eng-isl", "source_url": TRAIN_URL,
            "doc_id": f"{TRAIN_ID}:{index_number}",
        })
    random.Random(args.seed).shuffle(rows)
    required = args.train_size + args.dev_size
    if len(rows) < required:
        raise ValueError(f"Only {len(rows)} eligible pairs; requested {required}. Reduce train/dev sizes.")
    train, dev = rows[:args.train_size], rows[args.train_size:required]
    for row in train:
        row.update(split="train", usage="training")
    for row in dev:
        row.update(split="dev", usage="development_only")
    destination = ROOT / "data" / "processed"
    write_jsonl(destination / "train.jsonl", train)
    write_jsonl(destination / "dev.jsonl", dev)
    write_json(destination / "train.manifest.json", {
        "recipe_url": RECIPE_URL, "recipe_sha256": sha256(recipe),
        "recipe_id": "wmt26-eng-isl", "dataset_id": TRAIN_ID,
        "mtdata_index_url": MTDATA_INDEX_URL, "mtdata_index_sha256": sha256(index),
        "archive_url": TRAIN_URL, "archive_sha256": sha256(archive),
        "raw_pairs": len(pairs), "eligible_unique_pairs": len(rows),
        "train_size": len(train), "dev_size": len(dev), "seed": args.seed,
        "train_sha256": sha256(destination / "train.jsonl"),
        "dev_sha256": sha256(destination / "dev.jsonl"),
        "split_policy": "normalized source disjoint, full WMT26 en-is test sources excluded",
        "dev_note": "held out from this recipe training corpus, not an official WMT26 dev split",
        "download_method": "exact OPUS URL generated by MTData index; no full recipe download",
    })
    print(f"Saved {len(train)} train and {len(dev)} dev pairs from WMT26's {TRAIN_ID} resource.", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=["test", "train", "all"])
    parser.add_argument("--limit", type=int, default=20, help="test documents; 0 = all matching documents")
    parser.add_argument("--max-chars", type=int, default=1500, help="source/document length filter; 0 disables")
    parser.add_argument("--allow-multimodal", action="store_true")
    parser.add_argument("--train-size", type=int, default=200)
    parser.add_argument("--dev-size", type=int, default=50)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()
    if min(args.limit, args.max_chars, args.train_size, args.dev_size) < 0:
        parser.error("sizes and limits must be nonnegative")
    if args.stage in {"test", "all"}:
        prepare_test(args)
    if args.stage in {"train", "all"}:
        prepare_train(args)


if __name__ == "__main__":
    main()
